"use client";

import React, { useRef } from 'react';
import { Printer, Share2, X, GraduationCap, CheckCircle2 } from 'lucide-react';

export default function FeeReceiptView({ receipt, student, onClose, currency = '₹', business }) {
  if (!receipt) return null;

  const defaultBiz = business || {
    business_name: 'Alkaa Business +',
    tagline: 'Institute & Business Accounting',
    phone: '+91 98765 43210',
    address: 'City Center Campus'
  };

  const handlePrint = () => {
    window.print();
  };

  const handleShareWhatsApp = () => {
    const message = `*FEE PAYMENT RECEIPT: ${receipt.receipt_number}*\n` +
      `*${defaultBiz.business_name}*\n` +
      `Student Name: ${student?.name || receipt.student_name}\n` +
      `Course / Class: ${student?.course_or_details || 'Course Enrollment'}\n` +
      `Payment Date: ${receipt.payment_date || 'Today'}\n` +
      `---------------------------\n` +
      `*Amount Paid: ${currency}${receipt.amount}*\n` +
      `Payment Mode: ${String(receipt.payment_mode || 'Cash').toUpperCase()}\n` +
      (student?.due_amount !== undefined ? `Remaining Due: ${currency}${Math.max(0, student.due_amount - receipt.amount)}\n` : '') +
      `---------------------------\n` +
      `Receipt generated by Alkaa Business +.`;

    const phone = student?.phone ? student.phone.replace(/[^0-9]/g, '') : '';
    const url = phone
      ? `https://wa.me/${phone}?text=${encodeURIComponent(message)}`
      : `https://wa.me/?text=${encodeURIComponent(message)}`;

    window.open(url, '_blank');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 bg-slate-950/85 backdrop-blur-md overflow-y-auto animate-fadeIn">
      <div className="w-full max-w-lg bg-slate-900 border border-slate-800 rounded-3xl shadow-2xl overflow-hidden my-auto">
        {/* Controls */}
        <div className="no-print p-4 bg-slate-800/80 border-b border-slate-700/80 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <GraduationCap className="w-5 h-5 text-indigo-400" />
            <span className="font-bold text-white text-sm">
              Fee Receipt: {receipt.receipt_number}
            </span>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1 px-3 py-1.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow-md active:scale-95 transition-all"
            >
              <Printer className="w-4 h-4" />
              <span>Print</span>
            </button>
            <button
              onClick={handleShareWhatsApp}
              className="flex items-center gap-1 px-3 py-1.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold shadow-md active:scale-95 transition-all"
            >
              <Share2 className="w-4 h-4" />
              <span>WhatsApp</span>
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded-xl text-slate-400 hover:text-white hover:bg-slate-700 transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Printable Card */}
        <div className="p-4 sm:p-8 bg-slate-950/40">
          <div className="printable-area mx-auto bg-white text-slate-900 rounded-2xl p-6 font-sans border border-slate-200 shadow-xl max-w-md">
            {/* Header */}
            <div className="border-b border-slate-200 pb-3 text-center">
              <h1 className="text-xl font-black text-indigo-950 tracking-tight">
                {defaultBiz.business_name}
              </h1>
              <p className="text-[11px] text-slate-500 font-medium">{defaultBiz.tagline}</p>
              <p className="text-[10px] text-slate-400">{defaultBiz.address}</p>
              <div className="mt-2 inline-block px-3 py-0.5 rounded-full bg-indigo-100 text-indigo-800 text-[11px] font-bold uppercase tracking-wider">
                Official Fee Receipt
              </div>
            </div>

            {/* Receipt Info */}
            <div className="py-3 border-b border-slate-100 text-xs flex justify-between">
              <div>
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Receipt No</span>
                <span className="font-bold text-slate-800">{receipt.receipt_number}</span>
              </div>
              <div className="text-right">
                <span className="text-slate-400 block text-[10px] uppercase font-bold">Date</span>
                <span className="font-medium text-slate-700">{receipt.payment_date || new Date().toLocaleDateString()}</span>
              </div>
            </div>

            {/* Student Info */}
            <div className="py-3 border-b border-slate-100 text-xs space-y-1">
              <div className="flex justify-between">
                <span className="text-slate-500">Student Name:</span>
                <span className="font-bold text-slate-800">{student?.name || receipt.student_name}</span>
              </div>
              {student?.course_or_details && (
                <div className="flex justify-between">
                  <span className="text-slate-500">Course / Class:</span>
                  <span className="font-medium text-slate-700">{student.course_or_details}</span>
                </div>
              )}
              {student?.phone && (
                <div className="flex justify-between">
                  <span className="text-slate-500">Contact:</span>
                  <span className="text-slate-600">{student.phone}</span>
                </div>
              )}
            </div>

            {/* Payment Details */}
            <div className="py-3 border-b border-slate-100">
              <div className="flex justify-between items-center py-1">
                <span className="text-xs font-semibold text-slate-600">Amount Received:</span>
                <span className="text-lg font-black text-emerald-600">{currency}{Number(receipt.amount).toFixed(2)}</span>
              </div>
              <div className="flex justify-between items-center text-xs text-slate-500 pt-1">
                <span>Payment Mode:</span>
                <span className="font-bold uppercase text-slate-700">{receipt.payment_mode || 'Cash'}</span>
              </div>
              {receipt.notes && (
                <div className="mt-2 p-2 bg-slate-50 rounded text-[11px] text-slate-600">
                  <span className="font-semibold">Note:</span> {receipt.notes}
                </div>
              )}
            </div>

            {/* Signature & Seal */}
            <div className="pt-6 flex justify-between items-end text-[10px] text-slate-400">
              <div className="flex items-center gap-1 text-emerald-600">
                <CheckCircle2 className="w-4 h-4" />
                <span className="font-bold uppercase">Payment Verified</span>
              </div>
              <div className="text-center">
                <div className="w-24 border-b border-slate-400 mb-1"></div>
                <span>Authorized Signatory</span>
              </div>
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="no-print p-4 bg-slate-900 border-t border-slate-800 flex justify-end">
          <button
            onClick={onClose}
            className="px-5 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-white font-medium text-xs transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
